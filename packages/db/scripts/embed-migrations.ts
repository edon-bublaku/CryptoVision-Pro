/**
 * Bundles packages/db/drizzle/*.sql into src/migrations.gen.ts so migrations ship inside the
 * server bundle (Next.js standalone, in-process worker) without reading files at runtime.
 * Run automatically by `pnpm db:generate`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const journal = JSON.parse(readFileSync(`${root}drizzle/meta/_journal.json`, "utf8")) as { entries: { tag: string; when: number; breakpoints: boolean }[] };
const entries = journal.entries.map((e) => ({ tag: e.tag, when: e.when, breakpoints: e.breakpoints, sql: readFileSync(`${root}drizzle/${e.tag}.sql`, "utf8") }));
const out = `// Generated by scripts/embed-migrations.ts — do not edit. Source: packages/db/drizzle.\nexport const MIGRATIONS: { tag: string; when: number; breakpoints: boolean; sql: string }[] = ${JSON.stringify(entries, null, 2)};\n`;
writeFileSync(`${root}src/migrations.gen.ts`, out);
console.info(`embedded ${entries.length} migrations`);
